#!/usr/bin/env python3
"""Generate only the local clock UI glyph subset. Pillow is build-time only."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
# Rasterized locally for this device; the full host font is not bundled.
CJK='/System/Library/Fonts/STHeiti Light.ttc'
NUM='/System/Library/Fonts/Supplemental/Arial.ttf'
chars='年月日星期一二三四五六上下午夜时钟设置间制显示主题留白翻页历定反色开关启用结束全天保存返回确认选择加长按取消失败异常重新尝试自动计算分钟小时无时光有所得按项K'
import re
chars+=''.join(re.findall(r'[\u4e00-\u9fff]',(ROOT/'user/src/clock_render.c').read_text()))
chars=''.join(sorted(set(chars+'0123456789: /-+<>K')))
small=ImageFont.truetype(CJK,16)
out=['#ifndef UI_FONT_H','#define UI_FONT_H','#include <stdint.h>',
     '/* Generated by tools/make_fonts.py from local font subsets. */',
     'typedef struct { uint16_t code; uint8_t width; uint16_t rows[16]; } SmallGlyph;',
     'static const SmallGlyph small_glyphs[] = {']
for c in chars:
 w=8 if ord(c)<128 else 16
 im=Image.new('L',(w,16),255)
 d=ImageDraw.Draw(im)
 box=small.getbbox(c)
 d.text(((w-small.getlength(c))/2,(16-(box[3]-box[1]))//2-box[1]),c,font=small,fill=0)
 rows=[sum((1<<(15-x)) for x in range(w) if im.getpixel((x,y))<155) for y in range(16)]
 out.append('    {0x%04x,%d,{%s}}, /* %s */'%(ord(c),w,','.join('0x%04x'%r for r in rows),c))
out+=['};','#define SMALL_GLYPH_COUNT (sizeof small_glyphs / sizeof small_glyphs[0])']
for name,size,w,h in [('large',66,38,52),('medium',40,24,32)]:
 f=ImageFont.truetype(NUM,size)
 out.append('static const uint8_t %s_digits[11][%d] = {'%(name,((w+7)//8)*h))
 for c in '0123456789:':
  im=Image.new('L',(w,h),255);d=ImageDraw.Draw(im);box=f.getbbox(c)
  d.text(((w-f.getlength(c))/2,(h-(box[3]-box[1]))//2-box[1]),c,font=f,fill=0)
  data=[]
  for y in range(h):
   for xb in range((w+7)//8):
    data.append(sum(0x80>>b for b in range(8) if xb*8+b<w and im.getpixel((xb*8+b,y))<155))
  out.append('    {'+','.join(str(x) for x in data)+'},')
 out.append('};')
out.append('#endif')
(ROOT/'user/inc/ui_font.h').write_text('\n'.join(out)+'\n')
print('Generated',len(chars),'Chinese/ASCII glyphs and two digit sizes')
