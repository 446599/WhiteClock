#!/usr/bin/env python3
"""Generate the seven selected one-bit themes for the streaming MCU renderer."""
import hashlib
import json
from pathlib import Path
import struct

from PIL import Image

import theme_memory as memory
import theme_selected_memory as codec

ROOT = memory.ROOT
SELECTED = (1, 3, 11, 15, 16, 18, 20)


def font_name(key):
    kind, size, scale = key
    suffix = "" if scale == 1 else "_" + str(round(scale * 100))
    return f"TF_{kind.upper()}_{size}{suffix}"


def pack_image(image):
    image = image.convert("1")
    # Every physical panel row can now be read as consecutive packed bytes.
    current = image.transpose(Image.Transpose.ROTATE_90)
    tiled = memory.verified_bitmap(current)
    kind = {0: 7, 1: 5, 2: 6}[tiled[0]]
    choices = [struct.pack("<BHH", kind, *image.size) + tiled[5:]]
    raw = current.tobytes()
    encoded = codec.block_encode(raw, (current.width + 7) // 8)
    assert codec.block_decode(encoded) == raw
    choices.append(struct.pack("<BHH", 4, *image.size) + encoded)
    return min(choices, key=len)


def array(name, data):
    lines = [f"static const uint8_t {name}[] = {{"]
    for start in range(0, len(data), 24):
        lines.append("    " + ",".join(str(x) for x in data[start:start + 24]) + ",")
    lines.append("};")
    return lines


def main():
    output = ROOT / "build/theme-assets"
    output.mkdir(parents=True, exist_ok=True)
    requests = {}
    images = []
    definitions = []
    # The 24-hour label becomes live when the user selects 12-hour mode.
    memory.DYNAMIC_LABELS[20].add("LOCAL / 24H")
    for number in SELECTED:
        background, fonts = memory.capture_theme(number)
        definitions.append(f"#define TB_{number:02d} {len(images)}u")
        images.append((f"background-{number:02d}", background))
        for key, chars in fonts.items():
            requests.setdefault(key, set()).update(chars)
    # The day-of-month is unsigned numeric; it does not need punctuation glyphs.
    requests[("bold", 48, 1.0)] = set("0123456789")
    requests[("mono", 9, 1.0)].update("AMP")
    font_records = []
    font_metadata = []
    metadata_arrays = []
    for key, chars in requests.items():
        encoded = memory.atlas(*key, chars)
        count, cell_w, cell_h, columns, rows = struct.unpack_from("<HHHHH", encoded)
        offset = 10 + count * 10
        image = memory.decode_bitmap(encoded[offset:])
        index = len(font_records)
        definitions.append(f"#define {font_name(key)} {index}u")
        name = f"theme_metrics_{index}"
        metadata_arrays += array(name, encoded[10:offset])
        font_records.append(f"    {{{name},{len(images)}u,{count}u,{cell_w}u,{cell_h}u,{columns}u}},")
        font_metadata.append({"id": index,"image": len(images),"cell_w": cell_w,"cell_h": cell_h,
                              "columns": columns,"glyphs": [list(struct.unpack_from("<HBBhhH", encoded, 10 + i * 10)) for i in range(count)]})
        images.append((f"font-{index}", image))
    lines = ["#ifndef THEME_ASSETS_H", "#define THEME_ASSETS_H",
             "/* Generated by tools/make_theme_assets.py; DejaVu and Unifont notices accompany releases. */",
             "#define THEME_DECODE_BYTES 512u", f"#define THEME_BACKGROUND_IMAGES {len(SELECTED)}u", *definitions, *metadata_arrays]
    manifest = []
    for index, (name, image) in enumerate(images):
        data = pack_image(image)
        lines += array(f"theme_image_{index}", data)
        image.save(output / f"{index:02d}-{name}.png")
        manifest.append({"id": index, "name": name, "size": list(image.size), "encoded_bytes": len(data),
                         "encoding": data[0],
                         "sha256": hashlib.sha256(image.tobytes()).hexdigest()})
    lines += ["static const uint8_t *const theme_images[] = {"]
    lines += [f"    theme_image_{index}," for index in range(len(images))]
    lines += ["};", "static const ThemeFont theme_fonts[] = {", *font_records, "};", "#endif", ""]
    (ROOT / "user/inc/theme_assets.h").write_text("\n".join(lines))
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (output / "fonts.json").write_text(json.dumps(font_metadata, indent=2) + "\n")
    print(f"Generated {len(images)} one-bit images, {len(font_records)} subset fonts; "
          f"{sum(item['encoded_bytes'] for item in manifest)} bitmap bytes; no full framebuffer.")


if __name__ == "__main__":
    main()
